// Monthly Revenue Trend Aggregation API
app.get("/api/revenue/monthly-trend", async (req, res) => {
  try {
    const clientID = req.query.clientID || "jurgen-westerveld";
    const months = parseInt(req.query.months, 10) || 6;

    // Fetch user orders and invoices
    const [ordersSnap, invoicesSnap] = await Promise.all([
      db.collection("users").doc(clientID).collection("orders").get(),
      db.collection("users").doc(clientID).collection("invoices").get()
    ]);

    const orders = ordersSnap.docs.map(d => d.data());
    const invoices = invoicesSnap.docs.map(d => d.data());

    const result = [];
    const monthNames = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

    for (let i = months - 1; i >= 0; i--) {
      const d = new Date();
      d.setMonth(d.getMonth() - i);
      const mIdx = d.getMonth();
      const y = d.getFullYear();

      const matchingOrders = orders.filter(o => {
        const od = new Date(o.timestamp || o.createdAt || 0);
        return od.getMonth() === mIdx && od.getFullYear() === y;
      });

      const matchingInvoices = invoices.filter(inv => {
        const id = new Date(inv.issueDate || 0);
        return id.getMonth() === mIdx && id.getFullYear() === y;
      });

      const orderRevenue = matchingOrders.reduce((sum, o) => sum + (Number(o.amount || o.totalAmount) || 0), 0);
      const billedRevenue = matchingInvoices.reduce((sum, inv) => sum + (Number(inv.totalAmount) || 0), 0);

      result.push({
        monthShort: monthNames[mIdx],
        year: y,
        orderRevenue,
        billedRevenue,
        totalRevenue: orderRevenue + billedRevenue,
        orderCount: matchingOrders.length
      });
    }

    return res.json({ success: true, clientID, months, trend: result });
  } catch (error) {
    console.error("Error computing revenue trend:", error);
    return res.status(500).json({ error: error.message });
  }
});

