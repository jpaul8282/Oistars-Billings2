/**
 * Triggered whenever a new Order is placed in Cloud Firestore:
 * - Auto-generates a corresponding Invoice record
 * - Decrements catalog stock quantities
 * - Records an automated payment settlement
 */
exports.onOrderCreated = functions.firestore
  .document("users/{userId}/orders/{orderId}")
  .onCreate(async (snap, context) => {
    const orderData = snap.data();
    const { userId, orderId } = context.params;

    console.log(`[Order Trigger] Processing new order #${orderId} for client/user ${userId}`);

    const batch = db.batch();
    const now = Date.now();
    const invoiceId = orderData.invoiceId || `INV-${String(now % 100000).padStart(5, "0")}`;
    const amount = Number(orderData.amount || orderData.totalAmount || 0);

    // 1. Auto-generate paid invoice in user's billing records
    const invoiceRef = db.collection("users").doc(userId).collection("invoices").doc(invoiceId);
    batch.set(invoiceRef, {
      id: invoiceId,
      userId: userId,
      clientId: orderData.clientID || userId,
      clientName: orderData.customerName || "Store Customer",
      clientEmail: orderData.customerEmail || "",
      status: "PAID",
      issueDate: now,
      dueDate: now,
      currency: "EUR",
      totalAmount: amount,
      amountPaid: amount,
      subtotal: Math.round((amount / 1.21) * 100) / 100,
      taxTotal: Math.round((amount - (amount / 1.21)) * 100) / 100,
      discountTotal: 0.0,
      paymentTerms: "Store Checkout (Instant Settlement)",
      notes: `Auto-generated by Oistars Backend for Order #${orderId} (${orderData.shippingAddress || "N/A"})`,
      paidAt: now,
      createdAt: now
    }, { merge: true });

    // 2. Record instant payment ledger transaction
    const paymentId = `PAY-${String(now % 100000).padStart(5, "0")}`;
    const paymentRef = db.collection("users").doc(userId).collection("payments").doc(paymentId);
    batch.set(paymentRef, {
      id: paymentId,
      userId: userId,
      invoiceId: invoiceId,
      clientName: orderData.customerName || "Store Customer",
      amount: amount,
      currency: "EUR",
      paymentMethod: "Direct Store Checkout (Wero / SEPA Instant)",
      transactionRef: `ORDER-${orderId}`,
      paymentDate: now,
      notes: `Automated backend settlement for Order #${orderId}`
    }, { merge: true });

    // 3. Decrement stock for ordered products
    const productIDs = Array.isArray(orderData.productIDs) ? orderData.productIDs : [];
    for (const prodId of productIDs) {
      if (prodId) {
        const prodRef = db.collection("products").doc(prodId);
        batch.update(prodRef, {
          stockQuantity: admin.firestore.FieldValue.increment(-1)
        });
      }
    }

    try {
      await batch.commit();
      console.log(`[Order Trigger] Successfully processed invoice #${invoiceId} and payment #${paymentId} for order #${orderId}`);
    } catch (error) {
      console.error(`[Order Trigger] Error executing order fulfillment batch: ${error.message}`, error);
    }
  });

/**
 * Triggered on Order updates to synchronize fulfillment and ledger status.
 */
exports.onOrderUpdated = functions.firestore
  .document("users/{userId}/orders/{orderId}")
  .onUpdate(async (change, context) => {
    const before = change.before.data();
    const after = change.after.data();
    const { orderId, userId } = context.params;

    if (before.status !== after.status) {
      console.log(`[Order Trigger] Order #${orderId} status changed: ${before.status} -> ${after.status}`);
      // Audit log entry
      await db.collection("users").doc(userId).collection("audit_logs").add({
        eventType: "ORDER_STATUS_CHANGED",
        orderId: orderId,
        previousStatus: before.status,
        newStatus: after.status,
        timestamp: Date.now()
      });
    }
  });

